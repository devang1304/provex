"""H3: do KAIROS's alerted windows outside the labelled attack intervals contain attacker activity?

    python scripts/analyze_alert_windows.py --graphs artifact/graph_embeddings \
        --names artifact/explanations/node_mapping.json --kairos artifact/kairos_upstream/seed_0 \
        --pass1 results/pass1 --iocs ground_truth/cadets_e3/darpa/iocs.json --out results/analysis

For every alerted window, the analysis takes all of its anomalous events (score at or above the window
threshold, as KAIROS defines them) and reports how many touch DARPA's indicators.
- Specific indicators: attacker IPs, dropped files, implant process names.
- Shared names: process names that KAIROS merges with benign activity (nginx, sshd, sendmail).
- It also lists the window's most frequent anomalous entities.
No model is re-run.
"""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
import sys

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from provex.data import load_day, load_node_names  # noqa: E402
from provex.replay.alerts import window_threshold  # noqa: E402
from provex.replay.kairos_replay import Window  # noqa: E402

SHARED = {"nginx", "sshd", "sendmail"}


def ioc_matcher(iocs: dict):
    ips, files, procs = set(), set(), set()
    for att in iocs["attacks"].values():
        ips.update(att.get("ips", {}))
        files.update(att.get("files", []))
        procs.update(att.get("processes", []))

    def kind(label: str):
        t, _, name = label.partition(": ")
        if t == "netflow":
            return "ip" if name.rsplit(":", 1)[0] in ips else None
        if t == "file":
            return "file" if any(name == f or (not f.startswith("/") and name.endswith("/" + f)) for f in files) else None
        if t == "subject" and name in procs:
            return "shared_process" if name in SHARED else "process"
        return None
    return kind


def main():
    ap = argparse.ArgumentParser()
    for k in ("--graphs", "--names", "--kairos", "--pass1", "--iocs", "--out"):
        ap.add_argument(k, required=True)
    a = ap.parse_args()
    names = load_node_names(a.names)
    kind_of = ioc_matcher(json.loads(Path(a.iocs).read_text()))
    K = Path(a.kairos)
    alerts = json.loads((K / "alerts.json").read_text())
    gt_windows = {w for g in json.loads((K / "detection_metrics.json").read_text())["ground_truth"].values()
                  for w in g.get("windows", [])}
    by_day = {}
    for al in alerts:
        by_day.setdefault(al["day"], []).append(al)
    rows = []
    for day, als in sorted(by_day.items()):
        d = load_day(Path(a.graphs) / f"graph_{day}.TemporalData.simple")
        src, dst = d.src.numpy(), d.dst.numpy()
        P = torch.load(Path(a.pass1) / f"pass1_{day}.pt", weights_only=False)
        wins = [Window(**w) for w in P["windows"]]
        node_kind = {}

        def nk(i):
            if i not in node_kind:
                node_kind[i] = kind_of(names.get(int(i), ""))
            return node_kind[i]
        for al in sorted(als, key=lambda x: x["start_ns"]):
            w = next(w for w in wins if abs(w.start_t - al["start_ns"]) <= 1000 and abs(w.end_t - al["end_ns"]) <= 1000)
            tau = window_threshold(P["losses"], w)
            L = P["losses"][w.start_idx:w.end_idx].numpy()
            ev = np.nonzero(L >= tau)[0] + w.start_idx
            c = Counter()
            ents = Counter()
            for e in ev:
                ks = {nk(int(src[e])), nk(int(dst[e]))} - {None}
                specific = ks & {"ip", "file", "process"}
                c["specific"] += bool(specific)
                c["shared_only"] += bool(ks) and not specific
                for k in specific:
                    c[k] += 1
                ents[int(src[e])] += 1; ents[int(dst[e])] += 1
            n = len(ev)
            rows.append({"day": day, "window": al["window_file"], "start": al["start"], "end": al["end"],
                         "gt_window": al["window_file"] in gt_windows, "anomalous_events": n,
                         "frac_specific_ioc": c["specific"] / n if n else None,
                         "frac_shared_name_only": c["shared_only"] / n if n else None,
                         "by_kind": {k: c[k] for k in ("ip", "file", "process")},
                         "top_entities": [[names.get(i, f"node {i}"), m, nk(i)] for i, m in ents.most_common(8)]})
    O = Path(a.out); O.mkdir(parents=True, exist_ok=True)
    (O / "alert_windows.json").write_text(json.dumps(rows, indent=1))
    L = ["# Alerted windows against DARPA indicators (generated by scripts/analyze_alert_windows.py)", "",
         "| day | window start | labelled attack window | anomalous events | touching specific IOCs | shared names only | top entities |",
         "|---|---|---|---|---|---|---|"]
    for r in rows:
        fs = "n/a" if r["frac_specific_ioc"] is None else f"{r['frac_specific_ioc']:.1%}"
        fo = "n/a" if r["frac_shared_name_only"] is None else f"{r['frac_shared_name_only']:.1%}"
        te = "; ".join(f"`{lab}` {m}" + (f" ({k})" if k else "") for lab, m, k in r["top_entities"][:5])
        L.append(f"| {r['day']} | {r['start']} | {r['gt_window']} | {r['anomalous_events']} | {fs} | {fo} | {te} |")
    (O / "alert_windows.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()