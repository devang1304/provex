"""H1: what carries KAIROS's alert events? Summarises stage-1 records (class and channels per alert event).

    python scripts/analyze_stage1.py --records "results/stage1/expl/explanations_*.jsonl" \
        --iocs ground_truth/cadets_e3/darpa/iocs.json --out results/analysis

Channels per event, from exact hard deletions:
- full: the score KAIROS computed;
- no_neighbour_edges / no_history: one channel removed;
- nothing: every window item removed, keeping memory from before the window;
- memory_zero_uv: the two endpoints' memories zeroed;
- prior_only: no memory and no edges, i.e. the event type alone.
The class is window / prior / long_memory (provex.evaluate.metrics.alert_class).
"""
from __future__ import annotations

import argparse
import glob
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr


def ioc_sets(path):
    iocs = json.loads(Path(path).read_text())
    ips, files, procs = set(), set(), set()
    for att in iocs["attacks"].values():
        ips.update(att.get("ips", {})); files.update(att.get("files", [])); procs.update(att.get("processes", []))
    procs -= {"nginx", "sshd", "sendmail"}       # names KAIROS merges with benign activity

    def hit(label):
        t, _, name = label.partition(": ")
        if t == "netflow":
            return name.rsplit(":", 1)[0] in ips
        if t == "file":
            return any(name == f or (not f.startswith("/") and name.endswith("/" + f)) for f in files)
        return t == "subject" and name in procs
    return hit


def q(x, ps=(10, 50, 90)):
    return {str(p): float(np.percentile(x, p)) for p in ps} if len(x) else {}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--records", required=True); ap.add_argument("--iocs", required=True); ap.add_argument("--out", required=True)
    a = ap.parse_args()
    hit = ioc_sets(a.iocs)
    recs = {}
    for f in sorted(glob.glob(a.records)):
        for line in open(f, encoding="utf-8"):
            if line.strip():
                r = json.loads(line)
                recs[(r["event"]["day"], r["event"]["event"])] = r
    recs = list(recs.values())
    R = {"n": len(recs), "classes": Counter(r["alert_class"] for r in recs)}
    groups = defaultdict(Counter)
    for r in recs:
        e, o = r["event"], r["origin"]
        cls = r["alert_class"]
        groups[f"day {e['day']}"][cls] += 1
        groups["labelled attack window" if o.get("gt_window") else "other alerted window"][cls] += 1
        groups["endpoint is a labelled attack node" if r.get("gt_endpoint") else "no labelled endpoint"][cls] += 1
        groups["touches a DARPA indicator" if (hit(e["src_label"]) or hit(e["dst_label"])) else "no DARPA indicator"][cls] += 1
        groups[f"rank {o.get('rank')}"][cls] += 1
    R["by_group"] = {k: dict(v) for k, v in groups.items()}
    by_type = defaultdict(Counter)
    for r in recs:
        by_type[r["event"]["type"]][r["alert_class"]] += 1
    R["by_type"] = {k: dict(v) for k, v in by_type.items()}
    ctx = defaultdict(lambda: defaultdict(list))
    for r in recs:
        ch, cls = r["channels"], r["alert_class"]
        for name, ref in (("vs_prior", "prior_only"), ("vs_no_edges", "no_neighbour_edges"), ("vs_no_history", "no_history"),
                          ("vs_nothing", "nothing"), ("vs_memory_zero", "memory_zero_uv")):
            ctx[cls][name].append(ch["full"] - ch[ref])
        ctx[cls]["full_minus_tau"].append(ch["full"] - r["event"]["tau"])
    R["context_effect"] = {cls: {k: q(np.array(v)) for k, v in d.items()} for cls, d in ctx.items()}
    full = np.array([r["channels"]["full"] for r in recs]); prior = np.array([r["channels"]["prior_only"] for r in recs])
    R["spearman_full_vs_prior"] = float(spearmanr(full, prior).statistic) if len(recs) > 2 else None
    R["frac_context_raises_score"] = float(np.mean(full > prior)) if len(recs) else None
    tops = defaultdict(Counter)
    for r in recs:
        if r["alert_class"] == "window":
            e = r["event"]
            tops["window"][f"{e['src_label']} -{e['type'].replace('EVENT_', '')}-> {e['dst_label']}"] += 1
    R["window_class_examples"] = tops["window"].most_common(15)
    O = Path(a.out); O.mkdir(parents=True, exist_ok=True)
    (O / "stage1.json").write_text(json.dumps(R, indent=1, default=dict))
    L = ["# Stage 1: what carries KAIROS's alert events (generated by scripts/analyze_stage1.py)", "",
         f"Alert events: {R['n']}. Classes: {dict(R['classes'])}.", "",
         "| group | prior | window | long_memory |", "|---|---|---|---|"]
    for g, c in sorted(R["by_group"].items()):
        L.append(f"| {g} | {c.get('prior', 0)} | {c.get('window', 0)} | {c.get('long_memory', 0)} |")
    L += ["", "| event type | prior | window | long_memory |", "|---|---|---|---|"]
    for t, c in sorted(R["by_type"].items()):
        L.append(f"| {t} | {c.get('prior', 0)} | {c.get('window', 0)} | {c.get('long_memory', 0)} |")
    L += ["", "Context effect = full score minus the score with a channel removed (positive: that channel raises the anomaly).", "",
          "| class | measure | p10 | p50 | p90 |", "|---|---|---|---|---|"]
    for cls, d in R["context_effect"].items():
        for k, v in d.items():
            if v:
                L.append(f"| {cls} | {k} | {v['10']:.3f} | {v['50']:.3f} | {v['90']:.3f} |")
    L += ["", f"Spearman(full score, type-only score) = {R['spearman_full_vs_prior']}; "
          f"share of events whose context raises the score above the type-only score = {R['frac_context_raises_score']}.", "",
          "Most frequent window-class events:", ""]
    L += [f"- `{k}` x{v}" for k, v in R["window_class_examples"]]
    (O / "stage1.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()