"""KAIROS's own explanation: its attack-investigation summary graphs, for every alert (the incumbent baseline).

    python scripts/kairos_investigation.py --kairos artifact/kairos_upstream/seed_0 --out results/investigation

This reproduces KAIROS's attack_investigation.py, which the released code only runs on four
hard-coded 04-06 windows:
1. For each alerted window, read KAIROS's window file and keep the edges with loss above mean + 1.5 SD.
2. Merge nodes by name after the same path abstractions.
3. Split the union into Louvain communities (python-louvain, fixed seed). Each community is a
   candidate summary graph shown to the analyst.
Instead of rendering graphviz images, it records each community's nodes and edges.
"""
from __future__ import annotations

import argparse
import ast
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

import community.community_louvain as community_louvain
import networkx as nx

REPLACE = {
    "/run/shm/": "/run/shm/*",
    "/home/admin/.cache/mozilla/firefox/": "/home/admin/.cache/mozilla/firefox/*",
    "/home/admin/.mozilla/firefox": "/home/admin/.mozilla/firefox*",
    "/data/replay_logdb/": "/data/replay_logdb/*",
    "/home/admin/.local/share/applications/": "/home/admin/.local/share/applications/*",
    "/usr/share/applications/": "/usr/share/applications/*",
    "/lib/x86_64-linux-gnu/": "/lib/x86_64-linux-gnu/*",
    "/proc/": "/proc/*",
    "/stat": "*/stat",
    "/etc/bash_completion.d/": "/etc/bash_completion.d/*",
    "/usr/bin/python2.7": "/usr/bin/python2.7/*",
    "/usr/lib/python2.7": "/usr/lib/python2.7/*",
}


def abstract(name: str) -> str:
    for k, v in REPLACE.items():
        if k in name:
            return v
    return name


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kairos", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    K = Path(a.kairos)
    alerts = json.loads((K / "alerts.json").read_text())
    queues = defaultdict(list)
    for al in alerts:
        queues[(al["day"], al["queue_id"])].append(al)
    out = []
    for (day, qid), als in sorted(queues.items()):
        gg = nx.DiGraph()
        n_edges_in, n_anom = 0, 0
        for al in sorted(als, key=lambda x: x["start_ns"]):
            path = K / f"graph_{day}" / al["window_file"]
            edges = [ast.literal_eval(line.strip()) for line in open(path, encoding="utf-8") if line.strip()]
            n_edges_in += len(edges)
            losses = [e["loss"] for e in edges]
            thr = st.mean(losses) + 1.5 * st.pstdev(losses)
            for e in edges:
                if e["loss"] > thr:
                    n_anom += 1
                    s, d = abstract(e["srcmsg"]), abstract(e["dstmsg"])
                    gg.add_edge(s, d, loss=e["loss"], edge_type=e["edge_type"], time=e["time"], window=al["window_file"])
        part = community_louvain.best_partition(gg.to_undirected(), random_state=a.seed)
        comms = defaultdict(nx.DiGraph)
        for u, v, attr in gg.edges(data=True):
            for c in {part[u], part[v]}:
                comms[c].add_edge(u, v, **attr)
        rows = []
        for c, g in sorted(comms.items(), key=lambda kv: -kv[1].number_of_edges()):
            rows.append({"community": c, "nodes": sorted(g.nodes()), "n_nodes": g.number_of_nodes(),
                         "n_edges": g.number_of_edges(),
                         "edges": [{"src": u, "dst": v, "type": d["edge_type"], "loss": d["loss"], "time": d["time"]}
                                   for u, v, d in sorted(g.edges(data=True), key=lambda x: -x[2]["loss"])]})
        out.append({"day": day, "queue_id": qid, "n_windows": len(als), "window_edges": n_edges_in,
                    "anomalous_edges": n_anom, "graph_nodes": gg.number_of_nodes(), "graph_edges": gg.number_of_edges(),
                    "n_communities": len(rows), "community_sizes": [[r["n_nodes"], r["n_edges"]] for r in rows],
                    "communities": rows})
    O = Path(a.out); O.mkdir(parents=True, exist_ok=True)
    (O / "kairos_summary_graphs.json").write_text(json.dumps(out, indent=1))
    L = ["# KAIROS summary graphs for every alert (generated by scripts/kairos_investigation.py)", ""]
    for q in out:
        sizes = q["community_sizes"]
        L += [f"## Alert {q['day']} queue {q['queue_id']}: {q['n_windows']} windows, {q['window_edges']:,} events, "
              f"{q['anomalous_edges']:,} above threshold -> graph of {q['graph_nodes']} nodes / {q['graph_edges']} edges "
              f"in {q['n_communities']} communities", "",
              "Community sizes (nodes/edges), largest first: " + ", ".join(f"{n}/{e}" for n, e in sizes[:20]), ""]
    (O / "kairos_summary_graphs.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()