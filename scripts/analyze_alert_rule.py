"""H2: what KAIROS's alert rule would have to be to catch each attack, and what that costs.

    python scripts/analyze_alert_rule.py --kairos artifact/kairos_upstream --seeds 0,1,2 --out results/analysis

KAIROS chains windows that share rare suspicious nodes into queues, scores a queue as the product of
(window score + 1), and alerts on every window of a queue scoring above beta (100 in the released code).
Using KAIROS's own queue files, this script reports for each seed:
- each attack's best queue score (the beta it needs to be detected);
- a beta sweep: attacks detected and false-positive windows on the 8 test days and on the validation day;
- a single-window rule (window score above a threshold calibrated on the validation day).
No model is re-run.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import torch

BETAS = [1.5, 2, 3, 4, 5, 5.3, 6, 8, 10, 15, 20, 30, 31.1, 50, 100, 200, 1000, 1e4]


def queue_scores(path: Path):
    """window file name -> (best queue score, length of that queue)."""
    best = {}
    if not path.exists():
        return best
    for q in torch.load(path, weights_only=False):
        s = 1.0
        for w in q:
            s *= float(w["loss"]) + 1.0
        for w in q:
            name = Path(str(w.get("name", ""))).name
            if name not in best or s > best[name][0]:
                best[name] = (s, len(q))
    return best


def evaluate(scores, gt_by_day, test_days, rule):
    alerted = {(d, w) for d in test_days for w, v in scores[d].items() if rule(v)}
    gt = {(d, w) for d in test_days for w in gt_by_day.get(d, set())}
    tp, fp = alerted & gt, alerted - gt
    detected = sorted(d for d in test_days if any((d, w) in alerted for w in gt_by_day.get(d, set())))
    return {"alerted_windows": len(alerted), "tp_windows": len(tp), "fp_windows": len(fp),
            "fn_windows": len(gt - alerted), "attacks_detected": detected,
            "precision": len(tp) / len(alerted) if alerted else None, "recall": len(tp) / len(gt) if gt else None}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kairos", required=True); ap.add_argument("--seeds", default="0,1,2")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = {"betas": BETAS, "seeds": {}}
    for seed in [int(s) for s in a.seeds.split(",")]:
        K = Path(a.kairos) / f"seed_{seed}"
        det = json.loads((K / "detection_metrics.json").read_text())
        wins = json.loads((K / "windows.json").read_text())
        val_day = det["config"]["validation_graph"][len("graph_"):]
        test_days = [g[len("graph_"):] for g in det["config"]["queue_test_graphs"]]
        gt_by_day = {}
        for att, g in det["ground_truth"].items():
            gt_by_day.setdefault(g["graph"][len("graph_"):], set()).update(g.get("windows", []))
        days = [val_day] + test_days
        q = {d: queue_scores(K / f"graph_{d}_history_list") for d in days}
        # every window of the day: in no queue -> score 0 (cannot alert)
        qscore = {d: {w["window_file"]: q[d].get(w["window_file"], (0.0, 0))[0] for w in wins if w["day"] == d} for d in days}
        wscore = {d: {w["window_file"]: (w["anomalous_loss_avg"] or 0.0) for w in wins if w["day"] == d} for d in days}
        attacks = {}
        for att, g in det["ground_truth"].items():
            d = g["graph"][len("graph_"):]
            ws = g.get("windows", [])
            best = max((q[d].get(w, (0.0, 0)) for w in ws), default=(0.0, 0))
            attacks[att] = {"day": d, "gt_windows": len(ws), "best_queue_score": best[0], "best_queue_len": best[1],
                            "best_window_score": max((wscore[d].get(w, 0.0) for w in ws), default=0.0)}
        sweep = []
        for b in BETAS:
            r = evaluate(qscore, gt_by_day, test_days, lambda v, b=b: v > b)
            r["beta"] = b
            r["validation_fp_windows"] = sum(v > b for v in qscore[val_day].values())
            sweep.append(r)
        val_max_q = max(qscore[val_day].values(), default=0.0)
        val_max_w = max(wscore[val_day].values(), default=0.0)
        single = {"threshold_validation_max_window_score": val_max_w,
                  **evaluate(wscore, gt_by_day, test_days, lambda v: v > val_max_w)}
        out["seeds"][seed] = {"validation_day": val_day, "validation_max_queue_score": val_max_q,
                              "attacks": attacks, "beta_sweep": sweep, "single_window_rule": single,
                              "kairos_beta_100": evaluate(qscore, gt_by_day, test_days, lambda v: v > 100)}
    O = Path(a.out); O.mkdir(parents=True, exist_ok=True)
    (O / "alert_rule.json").write_text(json.dumps(out, indent=1))
    L = ["# KAIROS alert rule: what it takes to catch each attack (generated by scripts/analyze_alert_rule.py)", ""]
    for seed, s in out["seeds"].items():
        L += [f"## Seed {seed}", "", f"Validation day {s['validation_day']}: max queue score {s['validation_max_queue_score']:.2f}.", "",
              "| attack | day | GT windows | best queue score (needed beta) | queue length | best window score |", "|---|---|---|---|---|---|"]
        for att, x in s["attacks"].items():
            L.append(f"| {att} | {x['day']} | {x['gt_windows']} | {x['best_queue_score']:.4g} | {x['best_queue_len']} | {x['best_window_score']:.2f} |")
        L += ["", "| beta | attacks detected | TP windows | FP windows (test) | FP windows (validation) | precision | recall |", "|---|---|---|---|---|---|---|"]
        for r in s["beta_sweep"]:
            pr = "n/a" if r["precision"] is None else f"{r['precision']:.2f}"
            rc = "n/a" if r["recall"] is None else f"{r['recall']:.2f}"
            L.append(f"| {r['beta']:g} | {', '.join(r['attacks_detected']) or 'none'} | {r['tp_windows']} | {r['fp_windows']} | "
                     f"{r['validation_fp_windows']} | {pr} | {rc} |")
        sw = s["single_window_rule"]
        L += ["", f"Single-window rule (window score > validation max {sw['threshold_validation_max_window_score']:.2f}): "
              f"attacks {', '.join(sw['attacks_detected']) or 'none'}, TP {sw['tp_windows']}, FP {sw['fp_windows']}.", ""]
    (O / "alert_rule.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()